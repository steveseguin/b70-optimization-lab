#!/bin/bash
# packet 90b: the packet-90 sentry build plus the busy-window and decode
# vae/save timers (notes/2026-10-03-packet-90b-build.md). Same arms as 90:
# warm (3), settle, 120-prompt endurance over the ten fixtures, which keeps
# the wrong-clip trap (three handoff sentries) running while the timers
# measure per-card occupancy and the decode split.
#
# Differences from run-campaign-90.sh:
# - `sync` after each arm and after every 10 completed endure prompts (a
#   freeze zeroes unflushed files; f90 lost prompts 104-117 that way). The
#   earlier plan to drop syncs is withdrawn.
# - fresh index bases 204989 / 205089 (f90 used 202989 / 203089; the
#   highest index any earlier run used is 203193, load probes used 210000).
# - receipts are committed but NOT pushed.
# - graceful supervised stop at the end: quiesce, one SIGINT to the verified
#   launcher pid (the launcher runs ComfyUI in-process; there is no separate
#   child), bounded wait, no escalation. Skipped if FAULT.json is latched or
#   an arm ended in an execution error/timeout (process kept for review).
#
# Launch the server first (see the 90b note), then: bash run-campaign-90b.sh
# Do not edit this file while it runs (bash reads scripts incrementally).
set -u
R=/mnt/fast-ai/bench-results/ltx25-baseline-20260913
P=$R/prepared-encoder-busy-90b
MANIFEST=ab45830c64ed163044e64c2edf4cf835af58aaa14a1e25ed317211b192c8f749
RUN_NAME=encoder-server-busy-90b
RUN=$R/$RUN_NAME
LANE=/home/steve/llm-optimizations/experiments/ltx25-b70
REPO=/home/steve/llm-optimizations
PY=/home/steve/.venvs/ltx25-baseline/bin/python
OUT=$LANE/data/busy-90b
WARM_BASE=204989
ENDURE_BASE=205089
mkdir -p "$OUT"
step() { echo "=== $(date -u +%FT%TZ) $*"; }
save() { ( cd $REPO && git add experiments/ltx25-b70/data/busy-90b && git commit -q -m "LTX packet 90b: $1 receipts

Co-Authored-By: Claude Fable 5.1 <noreply@anthropic.com>" ) >/dev/null 2>&1 && step "committed $1" || step "commit of $1 failed (continuing)"; }

# Flush every 10 completed endure prompts. Ends when the stop flag appears;
# nothing is killed.
SYNC_FLAG=$OUT/.sync-watch-stop
sync_watch() { # prefix
  local last=0 n
  while [ ! -e "$SYNC_FLAG" ]; do
    n=$(ls -d $R/requests/$1-*/history.json 2>/dev/null | wc -l)
    if [ $((n / 10)) -gt $((last / 10)) ]; then sync; step "sync at $n completed $1 prompts"; last=$n; fi
    sleep 2
  done
}

ARM_RC=0
arm() { # name graph-arm count index-base [watch]
  step "$1: arm $2, $3 prompts, index base $4"
  local wpid=
  if [ "${5:-}" = watch ]; then rm -f "$SYNC_FLAG"; sync_watch $1 & wpid=$!; fi
  $PY -B $LANE/scripts/run-throughput-fixtures.py $1 --graph $P/graphs/graph-capture-all48-$2.json \
    --arm $2 --server-run $RUN --count $3 --index-base $4 --out $OUT
  ARM_RC=$?
  if [ -n "$wpid" ]; then touch "$SYNC_FLAG"; wait $wpid; rm -f "$SYNC_FLAG"; fi
  sync
  step "$1 finished rc=$ARM_RC; synced"
  if [ $ARM_RC -ne 0 ]; then save "$1 (rc=$ARM_RC)"; else save "$1"; fi
}

pid_is_server() { # pid ticks: the launcher we started, not a reused pid
  [ -r /proc/$1/cmdline ] || return 1
  tr '\0' ' ' < /proc/$1/cmdline | grep -q -- "serve-encoder.py .*--run-name $RUN_NAME" || return 1
  [ "$($PY -c "import sys;print(open('/proc/$1/stat').read().split(') ')[1].split()[19])")" = "$2" ]
}

graceful_stop() {
  [ -f $R/FAULT.json ] && { step "FAULT latched: server preserved for incident review, no stop"; return 1; }
  step "quiesce: waiting for an empty queue"
  for i in $(seq 1 120); do
    q=$(curl -sf -m 5 http://127.0.0.1:8188/queue) || break
    echo "$q" | $PY -c "import json,sys;d=json.load(sys.stdin);sys.exit(0 if not d['queue_running'] and not d['queue_pending'] else 1)" && break
    sleep 5
  done
  # The last prompts leave sampler/decode jobs in flight on the workers
  # (pipeline depth); a stop during in-flight graph work faulted the xe
  # engine on 09-21. Let them drain.
  step "drain 60 s for trailing in-flight pipeline jobs"
  sleep 60
  sync
  [ -f $R/FAULT.json ] && { step "FAULT latched during drain: no stop"; return 1; }
  pid_is_server $PID $TICKS || { step "pid $PID is not the $RUN_NAME launcher any more; nothing to stop"; return 1; }
  step "graceful stop: one SIGINT to launcher pid $PID"
  kill -INT $PID
  for i in $(seq 1 36); do [ -e /proc/$PID ] || break; sleep 5; done
  sync
  if [ -e /proc/$PID ]; then
    step "pid $PID still alive after 180 s; NOT escalating (bare kills have faulted the GPU). Inspect by hand."
    return 1
  fi
  step "server stopped"
}

[ "$(sha256sum $P/manifest.json | cut -d' ' -f1)" = "$MANIFEST" ] || { step "packet manifest differs from the reviewed one; refusing"; exit 1; }
/home/steve/llm-optimizations/scripts/check-b70-runtime-pm.sh || { step "runtime PM unsafe; refusing to run"; exit 1; }
step waiting for server health
for i in $(seq 1 360); do
  [ -f $R/FAULT.json ] && { step FAULT latched; exit 1; }
  curl -sf http://127.0.0.1:8188/queue >/dev/null 2>&1 && break
  sleep 5
done
curl -sf http://127.0.0.1:8188/queue >/dev/null || { step server never answered; exit 1; }
PID=$($PY -c "import json;print(json.load(open('$RUN/server-identity.json'))['pid'])")
TICKS=$($PY -c "import json;print(json.load(open('$RUN/server-identity.json'))['proc_start_ticks'])")
[ "$($PY -c "import json;print(json.load(open('$RUN/server-identity.json'))['source_packet_manifest_sha256'])")" = "$MANIFEST" ] \
  || { step "server on 8188 is not the 90b packet; refusing"; exit 1; }
pid_is_server $PID $TICKS || { step "server pid $PID does not match $RUN_NAME identity; refusing"; exit 1; }
step server pid $PID up
# Rest after construction: the 17:26 segfault hit 14 s into warm, right after
# construction's own component loads. Give the machine a quiet minute.
step "rest 60 s after construction"
sleep 60
arm f90b-warm pipe-samp2-tsh 3 $WARM_BASE
[ $ARM_RC -eq 0 ] || { step "warm failed rc=$ARM_RC; server left up for review"; exit 1; }
# Settle gap: the freezes hit at the warm->endure load step-change.
step "settle 60 s between arms"
sleep 60
arm f90b-endure pipe-samp2-tsh 120 $ENDURE_BASE watch
ENDURE_RC=$ARM_RC
if [ $ENDURE_RC -eq 0 ] || [ $ENDURE_RC -eq 3 ]; then
  graceful_stop
else
  step "endure ended rc=$ENDURE_RC (execution error/timeout): server left up for review, no stop"
fi
sync
step "campaign complete (endure rc=$ENDURE_RC)"
exit $ENDURE_RC
