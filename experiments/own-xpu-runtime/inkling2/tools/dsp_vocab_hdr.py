# writes src/dsp_vocab.hpp: the drafter head's built-in token list (dspark.hpp INK_DSP_VOCAB) as a bitmap over the
# vocabulary, from data/dsp-vocab-freq.txt (token id and count per line, most frequent first; counted with the model's
# tokenizer over ~18M tokens of local text: lab notes, man pages, package READMEs, the Python standard library,
# llama.cpp sources, site text, JSON records and a word list)
import sys
V = 200064
src, dst = sys.argv[1], sys.argv[2]
ids = sorted({int(l.split()[0]) for l in open(src) if l.strip()})
assert ids[0] >= 0 and ids[-1] < V
bits = [0] * ((V + 31) // 32)
for t in ids:
    bits[t >> 5] |= 1 << (t & 31)
with open(dst, 'w') as o:
    o.write('// generated by tools/dsp_vocab_hdr.py from data/dsp-vocab-freq.txt (%d tokens); do not edit\n' % len(ids))
    o.write('#pragma once\n#include <cstdint>\nnamespace ink {\n')
    o.write('inline constexpr int DSP_VOCAB_TOKENS = %d, DSP_VOCAB_BITS = %d;\n' % (len(ids), V))
    o.write('inline constexpr uint32_t dsp_vocab_bits[%d] = {\n' % len(bits))
    for i in range(0, len(bits), 8):
        o.write('    ' + ', '.join('0x%08x' % b for b in bits[i:i + 8]) + ',\n')
    o.write('};\n} // namespace ink\n')
print(len(ids), 'tokens')
