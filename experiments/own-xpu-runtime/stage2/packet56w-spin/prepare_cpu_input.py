#!/usr/bin/env python3
"""Restore only this candidate's generated CPU RoPE input; no parent writes."""
import hashlib
import json
import os
from pathlib import Path
import struct

P = Path(__file__).resolve().parent
ROOT = P.parents[3]
KEY = 'experiments/own-xpu-runtime/stage2/packet45-merged3/build/fusion-rope.hpp'

def main():
    assert os.getpriority(os.PRIO_PROCESS, 0) == 19
    assert set(os.sched_getaffinity(0)) <= set(range(8,16)) | set(range(24,32))
    seal = json.loads((P/'screen-seal.json').read_text())
    expected = seal['sources'][KEY]
    raw = (P/'rope.bf16').read_bytes()
    values = struct.unpack('<' + str(len(raw)//2) + 'H', raw)
    data = ('#pragma once\nnamespace rope_constants { inline constexpr int positions=32768; '
            'inline constexpr uint16_t table[]={' + ','.join(map(str,values)) + '};}\n').encode()
    assert hashlib.sha256(data).hexdigest() == expected
    target = P/'build/fusion-rope.hpp'
    target.parent.mkdir(exist_ok=True)
    assert target.parent.resolve().is_relative_to(P)
    inherited = ROOT/KEY
    if target.exists():
        assert hashlib.sha256(target.read_bytes()).hexdigest() == expected
    elif inherited.exists():
        assert hashlib.sha256(inherited.read_bytes()).hexdigest() == expected
        target.symlink_to(inherited)
    else:
        # A fresh checkout can rebuild with its own identical generated bytes.
        target.write_bytes(data)
    print(json.dumps(dict(passed=True, device_executed=False, generated_bytes=len(data),
        generated_sha256=expected, source='rope.bf16',
        source_sha256=hashlib.sha256(raw).hexdigest(),
        target=str(target), inherited_path=KEY,
        parent_modified=False)))

if __name__ == '__main__':
    main()
