"""CPU rehearsal of the packet184 device worker and its report (real two-rank host sessions).

Runs tp2_lifecycle.smoke() and tp2_lifecycle.lifecycle() -- the exact leg functions of the device
rows -- with a CPU environment: fresh --mini rank pairs of the gnu-host engine per leg (mini
selection), the device-free tool binary, sizes scaled to the mini context (K=8, M=6, R=4, a 7-token
delta), a private drain root per leg (never stage2/screen/v3), no device monitor and no oracle
(oracle gates report 'not applicable'). Then lifecycle_report.analyze() must pass on both runs, and
must FAIL with the expected first gate on six mutated copies (a flipped merged token, a flipped
append token, a flipped draft guess, a changed SREF blob hash, a changed S2b blob hash, a missing
leg teardown). Finally compact() and the report's request fields are exercised on one REAL device
request row of the parent line (lineage/parent-device-request.json, packet183's 2026-10-22 lane-B
bracket). Receipt: v5/evidence/worker-rehearsal.json. CPU limits as the other gates; a 1800 s bound.
"""
import copy, json, os, resource, shutil, sys, time
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import tp2_checkpoint as T
import tp2_lifecycle as L
import lifecycle_report as R
from p184_build_checkpoint import sha, save, limits, ROOT

W = HERE / 'build/worker-rehearsal'
sys.path.insert(0, str(T.P56))
import suite as SUITE  # noqa: E402  (vendored packet56 suite: retain_request_state)
import storage as STORAGE  # noqa: E402
STORAGE.admit = lambda extra, **unused: None
DEADLINE = time.monotonic() + 1800


class CpuEnv(L.Env):
    def __init__(self, output, kind):
        super().__init__(output, kind, HERE / 'build/tool/own-rt-ckpt-tool', HERE / 'tokenizer-identity.tsv')
        self.K, self.M, self.R = 8, 6, 4
        self.engine = HERE / 'build/gnu-host/own-rt-iq3'
        self.selection = HERE / 'lineage/mini/selection.json'
        self.pair = None

    def teardown_root(self, name):
        root = W / 'drain' / (self.kind + '-' + name)
        root.mkdir(parents=True)
        return root

    def check(self):
        assert time.monotonic() < DEADLINE, 'rehearsal deadline (1800 s)'

    def open_pair(self, name):
        limits()
        leg_out = self.output / 'legs' / name
        leg_out.mkdir(parents=True)
        pair = T.open_pair(T.cpu_args(self.engine, leg_out / 'ranks'), leg_out / 'ranks', self.engine, self.tokenizer, True, self.selection)
        pair.binary = self.tool
        pair.retainer = SUITE.retain_request_state        # the real retainer; storage admission is a CPU no-op
        self.pairs += 1
        return pair

    def prompt(self):
        return 'mini', [2, 5, 3, 7, 1]

    def oracle(self, prompt_id):
        return None

    def append_delta(self, history, pending):
        return [4, 9, 2, 11, 6, 3, 8], dict(delta_tokens=7, source='CPU mini delta', tp1_saved_history_sha256=None, tp1_pending_token=None)


def worker(kind):
    out = W / kind / 'run'
    out.mkdir(parents=True)
    root = out / 'checkpoints'
    root.mkdir()
    env = CpuEnv(out, kind)
    rows = (L.smoke if kind == 'smoke' else L.lifecycle)(env, out, root)
    rows.update(passed=True, device_executed=False, legs_launched=env.pairs, lane='cpu-rehearsal')
    save(out / 'lifecycle-inputs.json', rows)
    L.write_samples(out, rows)
    report = R.analyze(out)
    archive(out, kind)
    assert report['passed'], (kind, report['first_failed_gate'], report['gates'].get(report['first_failed_gate']))
    return out, rows, report


ARCHIVES = {}


def write_fixture_module():
    text = json.dumps(ARCHIVES, sort_keys=True)
    assert "'''" not in text
    (HERE / 'report_fixture_data.py').write_text('"""Generated by v5/lifecycle_rehearsal.py: report-contract fixtures captured from real CPU two-rank runs.\n'
                                                 'A Python module because ops/rehearse_entry.py\'s report sandbox reads repository .py sources only."""\n'
                                                 'import json\nFIXTURES = json.loads(r\'\'\'' + text + '\'\'\')\n')


def archive(run, kind):
    """Capture this real CPU run's report inputs as the report contract's fixture (report_fixture.py)."""
    files = {}
    for path in sorted(run.rglob('*')):
        rel = str(path.relative_to(run))
        if path.is_file() and (rel in ('lifecycle-inputs.json', 'lifecycle-samples.jsonl') or rel.endswith('/teardown.json') and rel.startswith('legs/')
                               or rel.endswith('/manifest.json') and (rel.startswith('checkpoints/') or '-manifest-copy/' in rel)):
            files[rel] = path.read_text()
    ARCHIVES[kind] = dict(schema='packet184.report-fixture.v1', kind=kind, files=files,
                          scope='captured from v5/lifecycle_rehearsal.py (CPU mini, real two-rank host pairs); fixture for v5/report-contract.json')


def mutate(run, kind, label, change, expected):
    copy_dir = W / 'mutated' / f'{kind}-{label}'
    shutil.copytree(run, copy_dir, symlinks=True)
    change(copy_dir)
    report = R.analyze(copy_dir)
    assert not report['passed'] and report['first_failed_gate'] == expected, (label, report['first_failed_gate'])
    return dict(kind=kind, mutation=label, first_failed_gate=report['first_failed_gate'])


def edit_inputs(fn):
    def apply(d):
        x = json.loads((d / 'lifecycle-inputs.json').read_text())
        fn(x)
        (d / 'lifecycle-inputs.json').write_text(json.dumps(x))
    return apply


def edit_manifest(cid, copy_dir=False):
    def apply(d):
        path = (d / (cid + '-manifest-copy') if copy_dir else d / 'checkpoints' / cid) / 'manifest.json'
        m = json.loads(path.read_text())
        b = m['ranks'][1]['blobs'][0]
        b['sha256'] = ('0' if b['sha256'][0] != '0' else '1') + b['sha256'][1:]
        path.write_text(json.dumps(m))
    return apply


def main():
    limits()
    os.environ['OMP_NUM_THREADS'] = '2'
    started = time.monotonic()
    shutil.rmtree(W, ignore_errors=True)
    W.mkdir(parents=True)
    smoke_run, smoke_rows, smoke_report = worker('smoke')
    print('worker smoke (2 legs) + report PASS', flush=True)
    life_run, life_rows, life_report = worker('lifecycle')
    print('worker lifecycle (3 legs) + report PASS', flush=True)
    write_fixture_module()
    flip = lambda xs, i: xs.__setitem__(i, (xs[i] + 1) % 16)
    negatives = [
        mutate(smoke_run, 'smoke', 'merged token', edit_inputs(lambda x: flip(x['legs'][1]['requests']['resume']['tokens'], 0)),
               'merged K+M == uninterrupted reference'),
        mutate(smoke_run, 'smoke', 'draft guess', edit_inputs(lambda x: x['legs'][1]['requests']['resume']['guesses'].__setitem__(0, -7)),
               'merged draft guesses == reference'),
        mutate(life_run, 'lifecycle', 'append token', edit_inputs(lambda x: flip(x['legs'][1]['requests']['append']['tokens'], 2)),
               'append == one-shot new reference[0:M]'),
        mutate(life_run, 'lifecycle', 'sref blob hash', edit_manifest('sref'), 'state: resumed chain S2 == one-shot SREF (all blobs, both ranks)'),
        mutate(life_run, 'lifecycle', 's2b blob hash', edit_manifest('s2b', copy_dir=True), 'state: repeat S2b == S2 (all blobs, both ranks)'),
        mutate(life_run, 'lifecycle', 'leg teardown missing', lambda d: (d / 'legs/leg2/teardown.json').unlink(), 'leg drained leg2'),
    ]
    print('report negatives PASS', len(negatives), flush=True)
    # The report's request fields on one REAL parent-line device request row.
    fixture = json.loads((HERE / 'lineage/parent-device-request.json').read_text())
    real = L.compact(fixture['request'])
    assert len(real['tokens']) == 128 and real['draft_rows'] == 87 + 128 - 2 and real['ttft_ms'] and real['decode_tok_s'], real
    assert all(g is None or isinstance(g, int) for g in real['guesses'])
    real_row = dict(tokens=len(real['tokens']), draft_rows=real['draft_rows'], ttft_ms=real['ttft_ms'], decode_tok_s=real['decode_tok_s'],
                    prompt_wall_ms=real['prompt_wall_ms'], origin=fixture['source'], origin_digest=fixture['source_sha256'])   # provenance only, not a pin (another packet's untracked device output)
    summary = dict(passed=True, device_executed=False, scope='CPU mini geometry, real two-rank host engine, the device rows\' own leg functions; not a device result',
                   seconds=round(time.monotonic() - started, 1),
                   smoke=dict(legs=smoke_rows['legs_launched'], gates=len(smoke_report['gates']), gate_names=sorted(smoke_report['gates']),
                              oracle_gates='not applicable on CPU (mini vocabulary)'),
                   lifecycle=dict(legs=life_rows['legs_launched'], gates=len(life_report['gates']), gate_names=sorted(life_report['gates'])),
                   negatives=negatives, real_device_request=real_row,
                   sources={str(p.relative_to(ROOT)): sha(p) for p in (Path(__file__).resolve(), HERE / 'tp2_lifecycle.py', HERE / 'lifecycle_report.py',
                            HERE / 'tp2_checkpoint.py', HERE / 'lineage/parent-device-request.json', HERE / 'lineage/append-delta.json')},
                   engine_sha256=sha(HERE / 'build/gnu-host/own-rt-iq3'), tool_sha256=sha(HERE / 'build/tool/own-rt-ckpt-tool'))
    save(HERE / 'evidence/worker-rehearsal.json', summary)
    shutil.rmtree(W)
    print('worker rehearsal PASS', summary['seconds'], 's')


if __name__ == '__main__':
    # No RLIMIT_AS here: the worker's inherited exec-limit guard (p184_v5_exec_limits) refuses native
    # launches under a finite address-space limit, exactly as on device.
    main()
