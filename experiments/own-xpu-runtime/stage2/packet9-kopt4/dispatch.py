#!/usr/bin/env python3
"""Diagnostic dispatch from measured round2 and round3 medians; no promotion."""
import hashlib
import json
from pathlib import Path
import statistics
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[3]
CENSUS=ROOT/'experiments/qwen38-flash-next-ud-iq3xxs-b70/packet1/tensor-census.json'
RECEIPTS=HERE.parent/'packet7-kopt2/receipts-card3-20261011'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def key(t):
    d=t['dimensions'];return (t['type_id'],d[1] if len(d)>1 else 1,d[0],d[2] if len(d)==3 else 1)
def is_gemv(t):
    if t['component'] in ('embedding','ple_lookup','norms'):return False
    return t['name'].endswith('.weight') and 'ssm_conv1d' not in t['name']
def calculate():
    tensors=json.loads(CENSUS.read_text())['tensors'];byname={t['name']:t for t in tensors}
    samples={};sources={str(CENSUS.relative_to(ROOT)):sha(CENSUS)}
    for layer in range(4):
        path=RECEIPTS/f'layer{layer}-kernels/native.json';raw=json.loads(path.read_text())
        if raw['error'] or not raw['teardown']['safe_to_exit']:raise ValueError('bad round2 receipt')
        sources[str(path.relative_to(ROOT))]=sha(path)
        for r in raw['kernels']:
            if r['variant'] not in ('kopt_sg32','splitk4_v1'):continue
            times=[(e['end_ns']-e['start_ns'])/1e6 for e in r['events']]
            if len(times)!=20 or min(times)<=0:raise ValueError('round2 event coverage')
            samples.setdefault(key(byname[r['name']]),{}).setdefault(r['variant'],[]).append(statistics.median(times))
    path=HERE.parent/'packet8-kopt3/receipts-card3-20261011/timing.json'
    raw=json.loads(path.read_text());sources[str(path.relative_to(ROOT))]=sha(path)
    if not raw['passed']:raise ValueError('round3 failed')
    for layer in raw['layers']:
        for r in layer['summary']['kernels']:
            samples.setdefault(key(byname[r['name']]),{}).setdefault(r['variant'],[]).append(r['median_ms'])
    table=[]
    for shape in sorted({key(t) for t in tensors if is_gemv(t)}):
        measured=samples.get(shape,{})
        medians={v:statistics.median(xs) for v,xs in measured.items()}
        variant=min(medians,key=medians.get) if medians else 'kopt_sg32'
        table.append(dict(key=list(shape),variant=variant,round2_round3_median_ms=medians,
            evidence='round2/3 shape medians; diagnostic selection' if medians else 'unmeasured shape; conservative SG32 fallback',
            candidates=['decode_const_'+('split4' if variant=='splitk4_v1' else 'sg32')+'_v1','decode_slm_'+('split4' if variant=='splitk4_v1' else 'sg32')+'_v1']))
    mapping=[]
    for t in tensors:
        if is_gemv(t):
            matches=[r for r in table if r['key']==list(key(t))]
            if len(matches)!=1:raise ValueError('ambiguous dispatch: '+t['name'])
            variant=matches[0]['variant'];kind='gemv'
        else:
            kind='lookup' if t['component'] in ('embedding','ple_lookup') else 'control'
            variant='lookup_existing' if kind=='lookup' else 'control_existing'
        mapping.append(dict(name=t['name'],key=list(key(t)),kind=kind,variant=variant))
    if len({t['name'] for t in mapping})!=len(tensors):raise ValueError('duplicate tensor')
    return dict(schema='own-runtime.iq3.packet9.dispatch.v1',source_sha256=sources,
        promoted=False,scope='operator dispatch only; no full-model parity claim',
        table=table,tensors=mapping)
VARIANTS=('kopt_sg32','splitk4_v1','decode_const_sg32_v1','decode_slm_sg32_v1','decode_const_split4_v1','decode_slm_split4_v1')
def header(data):
    rows=['  {'+','.join(map(str,r['key']))+','+str(VARIANTS.index(r['variant']))+'},' for r in data['table']]
    return """// Generated by dispatch.py; diagnostic best-of-round2/3, not a promoted runtime.
#pragma once
#include <stdexcept>
namespace iq3::kopt4 {
struct DispatchRow {unsigned type,rows,k,experts,variant;};
inline constexpr DispatchRow dispatch_table[]={
"""+'\n'.join(rows)+"""
};
inline unsigned dispatch_variant(unsigned type,unsigned rows,unsigned k,unsigned experts) {
 const DispatchRow* match=nullptr;
 for(const auto& r:dispatch_table)if(r.type==type && r.rows==rows && r.k==k && r.experts==experts){
  if(match)throw std::invalid_argument("ambiguous dispatch");match=&r;
 }
 if(!match)throw std::invalid_argument("unregistered production matrix");
 return match->variant;
}
}
"""
if __name__=='__main__':
    d=calculate();(HERE/'dispatch.json').write_text(json.dumps(d,indent=2)+'\n');(HERE/'dispatch.hpp').write_text(header(d))
    print(len(d['tensors']),'production tensors;',len(d['table']),'unique GEMV keys')
