"""Packet58-onecard-diet-engine: the one proposal row (one-load instruction-diet screen). Temporary queue planning
only; never a live queue. PROPOSAL ONLY: the device-window driver decides.

  --emit-only   write screen/proposals/proposed-p58-dietengine-one-card-A.txt and the ops/lane-queue copy
  (default)     verify both copies equal the generated bytes and plan them in a temporary queue dir
"""
import json, subprocess, sys, tempfile
from pathlib import Path
from build_engine import P, ROOT, sha, save, limits
Q = P / 'screen'; OPS = P.parents[1] / 'ops'; QUEUE = OPS / 'lane-queue'
NAME = 'proposed-p58-dietengine-one-card-A.txt'
JOB = 'packet58dietengine-one-card-v5-A'
HOST_REQUIRED = 100487123456
# Measured one-load v5 output of this exact harness shape (du -sb packet182 card0-182-v5-a, 2026-10-22,
# including its ignored run/ trees): 42,192,578 B; declared writes are twice that, as the line declares.
PARENT_V5_OUTPUT_BYTES = 42192578
# Same harness, same model load, same host, 2026-10-22: packet182's retained cold-start receipt (ignored run/ tree, host-local).
TIMING = 'experiments/own-xpu-runtime/stage2/packet182-onecard-kio-rebracket/screen/evidence/card0-182-v5-a/resident/WSCREEN/run/run/cold-start.json'


def document():
    from launch_env import library_path
    lib = library_path()
    job = dict(name=JOB, lane='A', argv=[
        '/usr/bin/python3', '-B', str((Q / 'queue_runner.py').relative_to(ROOT)),
        '--arm', 'resident', '--output', str(Q / 'evidence/card0-58de-v5-a/resident'),
        '--cache-maintenance', 'overlap', '--fault-review', '{REVIEW}',
        '--library-path', lib, '--authorized-device-window'],
        review=str((Q / 'fault_review.py').relative_to(ROOT)), env_extra={},
        planned_write_bytes=2 * PARENT_V5_OUTPUT_BYTES)
    job['plan'] = dict(
        host_required_available_bytes=HOST_REQUIRED, expected_seconds=[700, 1200], watchdog_seconds=3600,
        entry_rehearsal=dict(
            preparation_probe_note='Packet-private device-define CPU preparation of the real WSCREEN argv under Landlock '
                                   '(no /dev/dri, no /mnt) with the max23/max23+diet bracket at production size: '
                                   'packet58-onecard-diet-engine/evidence/preparation.json. The shared prepare_probe cannot admit this '
                                   'unranked one-card argv and private 4 MiB RoPE; keep its WARN explicit.',
            timing_evidence=[TIMING],
            binaries=[dict(path=str((P / 'build/device/own-rt-iq3').relative_to(ROOT)), sha256=sha(P / 'build/device/own-rt-iq3')),
                      dict(path=str((P / 'build/device/p58-cache-fixtures').relative_to(ROOT)), sha256=sha(P / 'build/device/p58-cache-fixtures'),
                           args=['--help'], returncode=0, contains='--output')]))
    raw = ('# PROPOSAL ONLY (packet58-onecard-diet-engine). CPU preparation never queues a live job.\n'
           '# Lane A card 0, whole host. PAUSE-B retained; endpoints stopped gracefully for one controlled window.\n'
           '# K1a/K1b then ONE load A0/B0/A1/B1/A2 = max23/max23+diet/max23/max23+diet/max23.\n'
           '# Fixed: 23,049,601,024-byte cache, BF16 KV, unchanged target/oracle, resident lookups, kernel I/O.\n'
           '# The sole treatment is expert_gateup=production|diet, switched at the drained view boundary.\n'
           '# 47 halfcache gate/up sites switch; layer 2 retains its other-layout kernel. Parent device images unchanged.\n'
           '# 12 x 128-token cold requests per view; all 60 exact. A0 excluded from warm comparison only.\n'
           '# Screen: both diet views >=1.005 x each warm control; drift <=3%; no kill rule.\n'
           '# Chain: also >=1.02 x EVERY control and >=37.33456224 tok/s (record 36.602512).\n'
           '# Kills: inexact output, DRM >30.5 GB, drift >3%, warm control <36.0, compute-window saving <5 us/layer,\n'
           '# or differing fills/bytes. No automatic rerun. Saving is attributed compute-window delta /48, not direct kernel time.\n'
           '# Plan 700-1200 seconds, watchdog3600. Host admission100,487,123,456 bytes +1 GiB at START.\n'
           '# Disk floor25GB after declared writes. No power, memory, swap or page-cache setting changes.\n'
           + json.dumps(job) + '\n')
    return job, raw


def main():
    limits()
    job, raw = document()
    local = Q / 'proposals' / NAME; external = QUEUE / NAME
    if '--emit-only' in sys.argv:
        local.parent.mkdir(exist_ok=True); local.write_text(raw); external.write_text(raw)
        print('emitted', external.relative_to(ROOT)); return
    assert local.read_text() == external.read_text() == raw, 'proposal bytes differ from the generated document'
    with tempfile.TemporaryDirectory(prefix='p58de-plan-') as tmp:
        (Path(tmp) / 'queue-A.txt').write_text(raw)
        cp = subprocess.run([sys.executable, '-B', str(QUEUE / 'lanequeue.py'), 'plan', '--lane', 'A', '--directory', tmp],
                            stdin=subprocess.DEVNULL, capture_output=True, text=True, cwd=ROOT, timeout=600)
    log = P / 'evidence/queue-plan-v5.log'; log.write_text(cp.stdout + cp.stderr)
    assert cp.returncode == 0, log.read_text()[-4000:]
    rows = [json.loads(line) for line in cp.stdout.splitlines() if line.startswith('{')]
    assert len(rows) == 1 and rows[0]['name'] == JOB and rows[0]['plan'] == 'passed' and rows[0]['storage_admission']['passed'], rows
    save(P / 'evidence/queue-plans.json', dict(passed=True, device_executed=False, temporary_queue=True, queued=False,
                                              records=[dict(proposal=str(external.relative_to(ROOT)), proposal_sha256=sha(external), plan=rows)]))
    print(json.dumps(rows[0]))


if __name__ == '__main__':
    main()
