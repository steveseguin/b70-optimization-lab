#!/usr/bin/env python3
"""Packet190 bootstrap: identity-rewritten copy of packet187's two-card record-chain harness.

Packet187 is the V3 record bundle (bundle 8 + packet153 static snapshot + packet186 V3) that set the
two-card record 60.659520 tok/s (LocalMaxxing cmvjvabyv040jrf01dricuz8s, chain device-cards01-p187-a,
2026-10-22). Packet190 copies that harness for packet189's k3x selection and engine, changing exactly the
six items packet189's README ("Record bundle on a chain-rule win") prescribes.

Copied (CPU-only file work; packet187 and its orchestration are read, never written):
  * stage2/packet187-record-bundle-v3 -> stage2/packet190-record-bundle-k3x, excluding build/, submission/,
    evidence/ (packet187's chain receipts and its two regenerated CPU receipts), orchestration-snapshot/,
    selections/ (the active view, regenerated), READY-FOR-DEVICE.json, device/ and gnu-host/ (hard links,
    regenerated), v3-native/ (replaced by k3x-native/), lineage/window-20261022 and lineage/packet187-copy.json
    (packet187's own device/copy history), the packet186 engine bindings in lineage-inputs/ (replaced by
    packet189's), the git-ignored link-targets/fixture archive (hard links, regenerated by guard_layout190.py)
    and the packet187-specific placement scripts (replaced by place_k3x.py / select_k3x.py);
    lineage-inputs/ otherwise stays byte-identical;
  * ops/packet187-orchestration -> ops/packet190-orchestration, excluding evidence/ (packet136's replay
    archive is hard-linked back afterwards), ready.json, READY-FOR-DEVICE.json, cpu-receipts.json,
    proposal.jsonl and inputs/packet186-native.json (replaced by inputs/packet189-native.json).
Text rewrites outside lineage-inputs/: packet187-record-bundle-v3 -> packet190-record-bundle-k3x,
packet187 -> packet190, p187 -> p190, P187_ -> P190_ and the module names *187 -> *190 (files renamed alike).
Receipt: lineage/packet190-copy.json.  Run once: python3 -B copy_packet190.py
"""
import hashlib, json, os, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
STAGE = HERE.parent
OPS = ROOT / 'experiments/own-xpu-runtime/ops'
SOURCES = [(STAGE / 'packet187-record-bundle-v3', HERE,
            {'build', 'submission', 'evidence', 'orchestration-snapshot', 'selections', 'READY-FOR-DEVICE.json', 'device', 'gnu-host',
             'v3-native', 'lineage/window-20261022', 'lineage/packet187-copy.json', 'lineage-inputs/link-targets',
             'lineage-inputs/fixture-archive.tar.gz', 'lineage-inputs/packet186-native.json', 'lineage-inputs/packet186-build.json',
             'copy_packet187.py', 'place_v3.py', 'select_v3.py'}),
           (OPS / 'packet187-orchestration', OPS / 'packet190-orchestration',
            {'evidence', 'ready.json', 'READY-FOR-DEVICE.json', 'cpu-receipts.json', 'proposal.jsonl', 'inputs/packet186-native.json'})]
REWRITES = [('packet187-record-bundle-v3', 'packet190-record-bundle-k3x'), ('packet187', 'packet190'), ('p187', 'p190'), ('P187_', 'P190_'),
            ('entry187', 'entry190'), ('seal187', 'seal190'), ('finalize187', 'finalize190'), ('policy187', 'policy190'),
            ('readiness187', 'readiness190'), ('submission187', 'submission190'), ('stream_gate187', 'stream_gate190'),
            ('compile_turn187', 'compile_turn190'), ('preparation187', 'preparation190'), ('ENTRY187', 'ENTRY190'),
            ('results187', 'results190'), ('guard_layout187', 'guard_layout190')]
SKIP = {'__pycache__'}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def rename(name):
    for a, b in REWRITES:
        name = name.replace(a, b)
    return name


def text(data):
    if b'\0' in data[:8192]:
        return None
    try:
        return data.decode('utf-8')
    except UnicodeDecodeError:
        return None


def main():
    if (HERE / 'chain_pipeline.py').exists() or (OPS / 'packet190-orchestration').exists():
        sys.exit('refusing: packet190 copy already exists')
    commit = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    receipt = dict(schema='packet190.copy.v1', device_executed=False, source_commit=commit, rewrites=REWRITES, trees=[])
    for src, dst, exclude in SOURCES:
        files, links, renamed, rewritten, skipped = {}, {}, [], [], []
        for path in sorted(src.rglob('*')):
            rel = path.relative_to(src).as_posix()
            parts = rel.split('/')
            if SKIP & set(parts) or any(rel == x or rel.startswith(x + '/') for x in exclude):
                if path.is_file() and not path.is_symlink() and not (SKIP & set(parts)):
                    skipped.append(rel)
                continue
            if path.is_dir() and not path.is_symlink():
                continue
            history = parts[0] == 'lineage-inputs'
            out_rel = rel if history else '/'.join(rename(p) for p in parts)
            if out_rel != rel:
                renamed.append([rel, out_rel])
            out = dst / out_rel
            out.parent.mkdir(parents=True, exist_ok=True)
            if path.is_symlink():
                os.symlink(os.readlink(path), out)
                links[out_rel] = os.readlink(path)
                continue
            data = path.read_bytes()
            before = sha(data)
            decoded = None if history else text(data)
            if decoded is not None:
                new = rename(decoded)
                if new != decoded:
                    data = new.encode('utf-8')
                    rewritten.append(out_rel)
            out.write_bytes(data)
            shutil.copymode(path, out)
            files[out_rel] = dict(source_digest=before, digest=sha(data))
        receipt['trees'].append(dict(source=str(src.relative_to(ROOT)), destination=str(dst.relative_to(ROOT)), file_count=len(files),
                                     rewritten=rewritten, renamed=renamed, symlinks=links, excluded_files=len(skipped),
                                     files=files))
        print(dst.relative_to(ROOT), 'files', len(files), 'rewritten', len(rewritten), 'links', len(links), 'excluded', len(skipped))
    # packet136's real submission evidence (5.6 MB) is needed by the submission rehearsal: hard link, no new bytes.
    archive = OPS / 'packet187-orchestration/evidence/packet136-chain-evidence.json.gz'
    (OPS / 'packet190-orchestration/evidence').mkdir(exist_ok=True)
    os.link(archive, OPS / 'packet190-orchestration/evidence/packet136-chain-evidence.json.gz')
    receipt['hard_links'] = {'ops/packet190-orchestration/evidence/packet136-chain-evidence.json.gz': dict(source=str(archive.relative_to(ROOT)), sha256=sha(archive.read_bytes()))}
    receipt['note'] = 'source_digest values record packet187 bytes at source_commit; they are provenance, not pins'
    (HERE / 'lineage').mkdir(exist_ok=True)
    (HERE / 'lineage/packet190-copy.json').write_text(json.dumps(receipt, indent=1) + '\n')


if __name__ == '__main__':
    main()
