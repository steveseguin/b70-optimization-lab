"""Packet182: the one proposal row (one-load v5). Temporary queue planning only; never a live queue.

  --emit-only   write screen/proposals/proposed-p182-one-card-A.txt and the ops/lane-queue copy
  (default)     verify both copies equal the generated bytes and plan them in a temporary queue dir
"""
import json, subprocess, sys, tempfile
from pathlib import Path
from build_engine import P, ROOT, sha, save, limits
Q = P / 'screen'; OPS = P.parents[1] / 'ops'; QUEUE = OPS / 'lane-queue'
NAME = 'proposed-p182-one-card-A.txt'
JOB = 'packet182-one-card-v5-A'
# Measured one-load v5 output of this harness family (du -sb card0-58as-v5-a, 2026-10-19; packet171b's was
# 40,127,717 B): declared writes are twice that, as packet176 declared.
PARENT_V5_OUTPUT_BYTES = 40170623
# Same harness, same model load, 2026-10-19 (load_and_pin_ms 211,768): packet171b's retained cold-start receipt.
TIMING = 'experiments/own-xpu-runtime/stage2/packet171b-onecard-cqcopy/screen/evidence/card0-171b-v5-a/resident/WSCREEN/run/run/cold-start.json'


def document():
    from launch_env import library_path
    lib = library_path()
    job = dict(name=JOB, lane='A', argv=[
        '/usr/bin/python3', '-B', str((Q / 'queue_runner.py').relative_to(ROOT)),
        '--arm', 'resident', '--output', str(Q / 'evidence/card0-182-v5-a/resident'),
        '--cache-maintenance', 'overlap', '--fault-review', '{REVIEW}',
        '--library-path', lib, '--authorized-device-window'],
        review=str((Q / 'fault_review.py').relative_to(ROOT)), env_extra={},
        planned_write_bytes=2 * PARENT_V5_OUTPUT_BYTES)
    job['plan'] = dict(
        host_required_available_bytes=98990252032, expected_seconds=[700, 1200], watchdog_seconds=7200,
        entry_rehearsal=dict(
            preparation_probe_note='Packet-private device-define CPU preparation of the real WSCREEN argv under Landlock '
                                   '(no /dev/dri, no /mnt): packet182-onecard-kio-rebracket/evidence/preparation.json. The shared '
                                   'prepare_probe cannot admit this unranked one-card argv and private 4 MiB RoPE; keep its WARN explicit.',
            timing_evidence=[TIMING],
            binaries=[dict(path=str((P / 'build/device/own-rt-iq3').relative_to(ROOT)), sha256=sha(P / 'build/device/own-rt-iq3')),
                      dict(path=str((P / 'build/device/p58-cache-fixtures').relative_to(ROOT)), sha256=sha(P / 'build/device/p58-cache-fixtures'),
                           args=['--help'], returncode=0, contains='--output')]))
    raw = ('# PROPOSAL ONLY (packet182). Never queued by preparation; the device-window driver decides.\n'
           '# Lane A, card 0, whole host; lane B paused (PAUSE-B stays through the v5 AND the win-path chain).\n'
           '# One-load v5 re-bracket of packet176 (unchanged device binary 1b41fb4d...): A = packet58as spin parent\n'
           '# (--foreground-io copy), B = spin + compute-kernel head load / tail store (--foreground-io kernel, no copy engine).\n'
           '# Why again: the packet176 bracket (B 35.982/35.981 vs warm A 34.621/34.640, +3.87%, 60/60 exact) never reached a\n'
           '# correct record chain (chain 176-a ran the parent poll/copy line: generator flag block after __main__), and its\n'
           '# evidence tree was removed with untracked files on 2026-10-19 21:42 EDT, so no chain can be derived from it.\n'
           '# Arms A0/B0/A1/B1/A2 = spin/spin-kio/spin/spin-kio/spin, 12 x 128-token requests per view, A0 exact warm-up.\n'
           '# Gate (unchanged): both B >= +0.5% over every warm A, drift <= 3%, 60/60 exact vs iq3-p49-split32-v1.\n'
           '# Win-path chain (prepared, NOT armed; chain/ARMING.md): only if min gain >= +2.0% and min B >= 1.02 x 34.573038.\n'
           '# Mechanism readout + packet182 fill split (filled vs unfilled tokens) kept on every outcome.\n'
           '# Expected ~13-14 min (packet176 v5 unit: 13 min 20 s); plan range 700-1200 s; watchdog 7200 s (queue runner).\n'
           '# Production admission 98,990,252,032 bytes including 8 GiB reserve (MemAvailable + 1 GiB at START). No settings changes.\n'
           '# Declared writes are twice the measured packet58as v5 output; retain 25 GB root free after reserved writes.\n'
           + json.dumps(job) + '\n')
    return job, raw


def main():
    limits()
    job, raw = document()
    local = Q / 'proposals' / NAME; external = QUEUE / NAME
    if '--emit-only' in sys.argv:
        local.parent.mkdir(exist_ok=True); local.write_text(raw); external.write_text(raw)
        print('emitted', external.relative_to(ROOT)); return
    assert local.read_text() == external.read_text() == raw, 'proposal bytes differ from the generated document'
    with tempfile.TemporaryDirectory(prefix='p182-plan-') as tmp:
        (Path(tmp) / 'queue-A.txt').write_text(raw)
        cp = subprocess.run([sys.executable, '-B', str(QUEUE / 'lanequeue.py'), 'plan', '--lane', 'A', '--directory', tmp],
                            stdin=subprocess.DEVNULL, capture_output=True, text=True, cwd=ROOT, timeout=600)
    log = P / 'evidence/queue-plan-v5.log'; log.write_text(cp.stdout + cp.stderr)
    assert cp.returncode == 0, log.read_text()[-4000:]
    rows = [json.loads(line) for line in cp.stdout.splitlines() if line.startswith('{')]
    assert len(rows) == 1 and rows[0]['name'] == JOB and rows[0]['plan'] == 'passed' and rows[0]['storage_admission']['passed'], rows
    save(P / 'evidence/queue-plans.json', dict(passed=True, device_executed=False, temporary_queue=True, queued=False,
                                              records=[dict(proposal=str(external.relative_to(ROOT)), proposal_sha256=sha(external), plan=rows)]))
    print(json.dumps(rows[0]))


if __name__ == '__main__':
    main()
