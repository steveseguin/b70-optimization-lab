#!/usr/bin/env python3
"""Packet195 bootstrap: identity-rewritten copy of packet190's two-card record-chain harness.

Packet190 is the k3x record bundle (bundle 8 + packet153 static snapshot + packet186 V3 + packet189 k3x) that set the
two-card record 62.345282 tok/s (LocalMaxxing cmvk51wfn001gng01fpbfy89q, chain device-cards01-p190-a, 2026-10-22).
Packet195 copies that harness for packet194's k3x-diet selection and engine, changing exactly the six items
packet194's README ("Record bundle on a chain-rule win (derive from packet190)") prescribes.

Copied (CPU-only file work; packet190 and its orchestration are read, never written):
  * stage2/packet190-record-bundle-k3x -> stage2/packet195-record-bundle-diet, excluding build/, submission/,
    evidence/ (packet190's chain receipts and its two regenerated CPU receipts), orchestration-snapshot/,
    selections/ (the active view, regenerated), READY-FOR-DEVICE.json, device/ and gnu-host/ (hard links,
    regenerated), k3x-native/ (replaced by diet-native/), analysis/ (packet190's own kernel studies),
    lineage/window-20261022 and lineage/packet190-copy.json (packet190's own device/copy history), the packet189
    engine bindings in lineage-inputs/ (replaced by packet194's), the git-ignored link-targets/fixture archive (hard
    links, regenerated by guard_layout195.py) and the packet190-specific placement scripts (replaced by
    place_diet.py / select_diet.py); lineage-inputs/ otherwise stays byte-identical;
  * ops/packet190-orchestration -> ops/packet195-orchestration, excluding evidence/ (packet136's replay archive is
    hard-linked back afterwards), ready.json, READY-FOR-DEVICE.json, cpu-receipts.json, proposal.jsonl and
    inputs/packet189-native.json (replaced by inputs/packet194-native.json).
Text rewrites outside lineage-inputs/: packet190-record-bundle-k3x -> packet195-record-bundle-diet, packet190 -> packet195,
p190 -> p195, P190_ -> P195_ and the module names *190 -> *195 (files renamed alike).
Receipt: lineage/packet195-copy.json.  Run once: python3 -B copy_packet195.py
"""
import hashlib, json, os, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
STAGE = HERE.parent
OPS = ROOT / 'experiments/own-xpu-runtime/ops'
SOURCES = [(STAGE / 'packet190-record-bundle-k3x', HERE,
            {'build', 'submission', 'evidence', 'orchestration-snapshot', 'selections', 'READY-FOR-DEVICE.json', 'device', 'gnu-host',
             'k3x-native', 'analysis', 'lineage/window-20261022', 'lineage/packet190-copy.json', 'lineage-inputs/link-targets',
             'lineage-inputs/fixture-archive.tar.gz', 'lineage-inputs/packet189-native.json', 'lineage-inputs/packet189-build.json',
             'copy_packet190.py', 'place_k3x.py', 'select_k3x.py'}),
           (OPS / 'packet190-orchestration', OPS / 'packet195-orchestration',
            {'evidence', 'ready.json', 'READY-FOR-DEVICE.json', 'cpu-receipts.json', 'proposal.jsonl', 'inputs/packet189-native.json'})]
REWRITES = [('packet190-record-bundle-k3x', 'packet195-record-bundle-diet'), ('packet190', 'packet195'), ('p190', 'p195'), ('P190_', 'P195_'),
            ('entry190', 'entry195'), ('seal190', 'seal195'), ('finalize190', 'finalize195'), ('policy190', 'policy195'),
            ('readiness190', 'readiness195'), ('submission190', 'submission195'), ('stream_gate190', 'stream_gate195'),
            ('compile_turn190', 'compile_turn195'), ('preparation190', 'preparation195'), ('ENTRY190', 'ENTRY195'),
            ('results190', 'results195'), ('guard_layout190', 'guard_layout195')]
SKIP = {'__pycache__'}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def rename(name):
    for a, b in REWRITES:
        name = name.replace(a, b)
    return name


def text(data):
    if b'\0' in data[:8192]:
        return None
    try:
        return data.decode('utf-8')
    except UnicodeDecodeError:
        return None


def main():
    if (HERE / 'chain_pipeline.py').exists() or (OPS / 'packet195-orchestration').exists():
        sys.exit('refusing: packet195 copy already exists')
    commit = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    receipt = dict(schema='packet195.copy.v1', device_executed=False, source_commit=commit, rewrites=REWRITES, trees=[])
    for src, dst, exclude in SOURCES:
        files, links, renamed, rewritten, skipped = {}, {}, [], [], []
        for path in sorted(src.rglob('*')):
            rel = path.relative_to(src).as_posix()
            parts = rel.split('/')
            if SKIP & set(parts) or any(rel == x or rel.startswith(x + '/') for x in exclude):
                if path.is_file() and not path.is_symlink() and not (SKIP & set(parts)):
                    skipped.append(rel)
                continue
            if path.is_dir() and not path.is_symlink():
                continue
            history = parts[0] == 'lineage-inputs'
            out_rel = rel if history else '/'.join(rename(p) for p in parts)
            if out_rel != rel:
                renamed.append([rel, out_rel])
            out = dst / out_rel
            out.parent.mkdir(parents=True, exist_ok=True)
            if path.is_symlink():
                os.symlink(os.readlink(path), out)
                links[out_rel] = os.readlink(path)
                continue
            data = path.read_bytes()
            before = sha(data)
            decoded = None if history else text(data)
            if decoded is not None:
                new = rename(decoded)
                if new != decoded:
                    data = new.encode('utf-8')
                    rewritten.append(out_rel)
            out.write_bytes(data)
            shutil.copymode(path, out)
            files[out_rel] = dict(source_digest=before, digest=sha(data))
        receipt['trees'].append(dict(source=str(src.relative_to(ROOT)), destination=str(dst.relative_to(ROOT)), file_count=len(files),
                                     rewritten=rewritten, renamed=renamed, symlinks=links, excluded_files=len(skipped),
                                     files=files))
        print(dst.relative_to(ROOT), 'files', len(files), 'rewritten', len(rewritten), 'links', len(links), 'excluded', len(skipped))
    # packet136's real submission evidence (5.6 MB) is needed by the submission rehearsal: hard link, no new bytes.
    archive = OPS / 'packet190-orchestration/evidence/packet136-chain-evidence.json.gz'
    (OPS / 'packet195-orchestration/evidence').mkdir(exist_ok=True)
    os.link(archive, OPS / 'packet195-orchestration/evidence/packet136-chain-evidence.json.gz')
    receipt['hard_links'] = {'ops/packet195-orchestration/evidence/packet136-chain-evidence.json.gz': dict(source=str(archive.relative_to(ROOT)), sha256=sha(archive.read_bytes()))}
    receipt['note'] = 'source_digest values record packet190 bytes at source_commit; they are provenance, not pins'
    (HERE / 'lineage').mkdir(exist_ok=True)
    (HERE / 'lineage/packet195-copy.json').write_text(json.dumps(receipt, indent=1) + '\n')


if __name__ == '__main__':
    main()
