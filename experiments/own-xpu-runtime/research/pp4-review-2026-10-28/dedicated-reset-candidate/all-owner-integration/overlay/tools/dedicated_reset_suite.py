def exact(left,right,check):
 left,right=Path(left),Path(right);before=[reader.identity(p.stat()) for p in (left,right)]
 base.require(before[0][2]==before[1][2],'cold payload extent')
 total=0
 with left.open('rb') as a,right.open('rb') as b:
  while True:
   check();x,y=a.read(1024**2),b.read(1024**2);base.require(x==y,'cold canonical payload bytes')
   if not x:break
   total+=len(x)
 base.require(before==[reader.identity(p.stat()) for p in (left,right)],'cold payload replaced')
 return total

def inventory(old,new,context):
 fields=('launch_extent','alternate_launch_extent')
 for key in fields:
  base.require(all(type(x)is int and 32<=x<=context and x%32==0 for x in (old[key],new[key])),'cold retained launch geometry')
 base.require({k:v for k,v in old.items()if k not in fields}=={k:v for k,v in new.items()if k not in fields},'cold non-cache inventory')
 return {k:dict(initial=old[k],retained=new[k]) for k in fields}

class Cold:
 def __init__(self,plan,guard):self.plan,self.guard,self.baseline=plan,guard,None
 def __call__(self,stages,provider,output):
  reset_all.target_reset.quiescent(stages);self.guard.check();found={};inventories={}
  for s in stages:
   s.command(4,position=SENTINEL)
   root=Path(getattr(s,'dedicated_native_output',s.spec['native_output']))
   path=root/f'state-{SENTINEL}';sources=reader.read_state(path)
   # Bank maps are allocated before READY and survive reset. Authenticate their
   # exact inventory and extents without dropping them from full-byte proof.
   stage=json.loads((root/'pipeline-stage.json').read_text())
   launch=json.loads((root/'launch-plan.json').read_text())
   banks=stage['inactive_alternate_banks']
   base.require(isinstance(banks,list)and all(isinstance(n,str)for n in banks)and len(banks)==len(set(banks)),'inactive bank manifest')
   buffers={b['name']:b for b in launch['buffers']}
   expected={'alternate-'+n+'.bin'for n in banks}
   base.require({n for n in sources if n.startswith('alternate-')}==expected,'exact inactive bank inventory')
   extents={row.split('\t')[0]:int(row.split('\t')[2])for row in (path/'state-index.tsv').read_text().splitlines()[1:]}
   for n in banks:
    base.require(n in buffers and n+'.bin'in extents and extents['alternate-'+n+'.bin']==extents[n+'.bin']==buffers[n]['bytes'],'inactive bank launch extent')
   found[str(s.spec['id'])]=dict(path=str(path),sources=sources)
   inventories[str(s.spec['id'])]=json.loads((root/'request-state-inventory.json').read_text())
  provider.control(4)
  path=Path(getattr(provider,'dedicated_native_output',provider.owner.spec['native_output']))/f'provider-dump-{provider.sequence}'
  found['provider']=dict(path=str(path),sources=reader.read_state(path))
  base.require(len(found['provider']['sources'])-1==73,'complete provider canonical inventory')
  current=dict(state=found,inventory=inventories);compared=0;cache={}
  if self.baseline is not None:
   for owner,row in found.items():
    old=self.baseline['state'][owner];base.require(row['sources']==old['sources'],'cold full source mapping')
    compared+=exact(Path(old['path'])/'state.bundle',Path(row['path'])/'state.bundle',self.guard.check)
   for owner,inv in inventories.items():cache[owner]=inventory(self.baseline['inventory'][owner],inv,self.plan['context'])
  # Canonical replicated globals are counted once; all physical copies are still
  # authenticated above and byte-compared independently. No bank exclusions.
  canonical={}
  for owner,row in found.items():
   if owner=='provider':continue
   for name,h in row['sources'].items():
    if name=='state.json' or name.startswith('alternate-'):continue
    base.require(name not in canonical or canonical[name]==h,'cold replicated source mismatch')
    canonical[name]=h
  base.require(len(canonical)==2065,'complete target canonical inventory')
  proof=dict(schema='ownrt.dedicated-cold-proof.v1',passed=True,target_canonical_sources=len(canonical),
   provider_canonical_sources=73,inactive_bank_sources=sum(sum(n.startswith('alternate-')for n in row['sources'])for owner,row in found.items()if owner!='provider'),full_payload_bytes_compared=compared,actual=current,
   retained_prepared_launch_cache=cache,compared_to_startup=self.baseline is not None)
  base.save(Path(output)/'cold-proof.json',proof)
  if self.baseline is None:self.baseline=current
  else:
   # Every removed payload is newly generated by this controller and has just
   # passed full reader verification and exact comparison to retained startup.
   aliases={}
   for owner,row in found.items():
    payload=Path(row['path'])/'state.bundle';aliases[str(payload)]=dict(bytes=payload.stat().st_size,identical_retained_payload=str(Path(self.baseline['state'][owner]['path'])/'state.bundle'))
   base.save(Path(output)/'cold-payload-reuse.json',dict(schema='ownrt.dedicated-cold-payload-reuse.v1',passed=True,files=aliases))
   for path in aliases:Path(path).unlink()
  return proof

def forecast(plan):
 # Registered per-owner ceilings come from native launch layouts; measured cold
 # extents are checked before request0. Never reduce planner admission floors.
 bounds=plan['dedicated_reset_payload_bounds']
 base.require(set(bounds)=={str(s['id'])for s in plan['stages']}|{'provider'} and
  all(type(n)is int and n>0 for n in bounds.values()),'registered actual layout payload bounds')
 base.require(bounds['provider']>=638509378 if plan['context']==262144 else bounds['provider']>0,'provider full state forecast')
 # Startup cold payloads + one transient cold set + final set + native
 # provider sealed baseline. Duplicate cold payloads are removed only after
 # full byte verification and durable exact-reuse receipt; metadata stays.
 sets=4 if plan.get('dedicated_request_indices')==[0,1,0] else 3
 needed=sets*sum(bounds.values())+bounds['provider']+64*1024**2
 base.require(plan.get('dedicated_reset_evidence_bytes',0)>=needed,'full suite cold/final evidence forecast')
 return needed

def admit_drive(stages,provider,plan,epoch):
 base.require(plan.get('persistent_requests')is True and epoch==plan.get('epoch') and not plan.get('dedicated_reset_poisoned'),'suite epoch/capability')
 selected=reset_all.authority(plan,plan.get('dedicated_prompt_index',epoch))
 base.require(plan.pop('dedicated_reset_ready',None)==(epoch,plan['request_sha256'],selected['prompt_sha256']),'one-shot all-owner reset readiness')
 from rolling_provider.dedicated_transport import HEADER,MAGIC,VERSION
 base.require(HEADER.unpack(bytes(provider.shared[:HEADER.size]))==(MAGIC,VERSION,128,0,provider.stream_bytes,len(stages),plan.get('speculative_depth',2),0,epoch,bytes.fromhex(plan['request_sha256']),bytes(56)),'actual admitted provider Header')
 for stage in stages:
  extent,header=base.prefill_layout(plan['prefill_rows'],stage.stream_bytes,plan.get('dedicated_prefill_slots',2))
  base.require(len(stage.prefill)==extent and bytes(stage.prefill[:len(header)])==header and not any(stage.prefill[len(header):]),'actual reset geometry before first OP15')

def run(stages,provider,plan,guard,output,bridge):
 base.require(plan.get('dedicated_reset_protocol')==reset_all.PROTOCOL and plan.get('persistent_requests')is True,'explicit dedicated suite capability')
 rows=plan['dedicated_requests'];base.require(isinstance(rows,list)and len(rows)==12,'exact twelve runtime-only requests')
 forecast(plan);cold=Cold(plan,guard);cold(stages,provider,output)
 for owner,row in cold.baseline['state'].items():base.require((Path(row['path'])/'state.bundle').stat().st_size<=plan['dedicated_reset_payload_bounds'][owner],'actual cold payload exceeds forecast')
 order=plan.get('dedicated_request_indices',list(range(12)))
 base.require(order==list(range(12)) or order==[0,1,0],'registered full suite or bounded A-B-A gate')
 records=[];previous=plan['request_sha256'];root=Path(output);first_state=None;first_outputs=None
 for index,prompt_index in enumerate(order):
  row=rows[prompt_index]
  base.require(set(row)=={'id','prompt_tokens','max_new'} and row['max_new']==512 and isinstance(row['id'],str),'no oracle suite request')
  selected=reset_all.authority(plan,prompt_index);prompt=row['prompt_tokens']
  base.require(isinstance(prompt,list)and len(prompt)==selected['prompt_tokens'] and all(type(t)is int and 0<=t<plan['vocab']for t in prompt),'suite actual prompt tokens')
  base.require(sha256(struct.pack('<'+'i'*len(prompt),*prompt)).hexdigest()==selected['prompt_sha256'],'suite supplied prompt bytes')
  request=plan['request_sha256'] if index==0 else sha256(json.dumps(dict(parent=plan['request_sha256'],suite=selected['suite_sha256'],index=index,prompt=selected['prompt_sha256']),sort_keys=True).encode()).hexdigest()
  dest=root/f'request-{index:02d}';dest.mkdir(mode=0o700)
  if index:
   reset_all.transition(stages,provider,plan,guard,dest,previous_epoch=index-1,previous_request=previous,epoch=index,request=request,prompt_index=prompt_index,cold_verify=cold)
  else:
   base.require(prompt==plan['prompt_tokens'],'startup request0 actual prompt')
   plan['dedicated_reset_ready']=(0,request,selected['prompt_sha256'])
  manifest=json.loads(Path(plan['dedicated_prompt_manifest']).read_text())
  request_plan=dict(plan,prompt_tokens=prompt,max_new=512,request_sha256=request,epoch=index,
   dedicated_prompt_index=prompt_index,dedicated_prefill_prompt=manifest[f'prompt_{prompt_index}_path'],dedicated_prefill_prompt_sha256=selected['prompt_sha256'])
  # Readiness is transferred, not cloned into another reusable process plan.
  request_plan['dedicated_reset_ready']=plan.pop('dedicated_reset_ready')
  for stage in stages:stage.plan=request_plan
  provider.plan=provider.owner.plan=request_plan
  # Retained original owner specs never change; per-request source paths do.
  result=bridge.drive(stages,provider,request_plan,guard,dest,epoch=index)
  if order==[0,1,0] and index in (0,2):
   state={}
   for stage in stages:
    stage.command(4,position=2147483646)
    path=Path(getattr(stage,'dedicated_native_output',stage.spec['native_output']))/'state-2147483646'
    state[str(stage.spec['id'])]=dict(path=str(path),sources=reader.read_state(path))
   provider.control(4)
   path=Path(getattr(provider,'dedicated_native_output',provider.owner.spec['native_output']))/f'provider-dump-{provider.sequence}'
   sources=reader.read_state(path)
   base.require(len(sources)-1==73,'repeated A complete provider canonical inventory')
   state['provider']=dict(path=str(path),sources=sources)
   outputs=result.get('output_ids')
   base.require(isinstance(outputs,list) and outputs and all(type(t)is int and 0<=t<plan['vocab']for t in outputs),'actual repeated A output IDs')
   if index==0:first_state=state;first_outputs=list(outputs)
   if index==2:
    base.require(outputs==first_outputs,'repeated A actual output IDs differ')
    compared=0;by_owner={}
    for owner,actual in state.items():
     initial=first_state[owner];base.require(actual['sources']==initial['sources'],'repeated A complete source mapping')
     by_owner[owner]=exact(Path(initial['path'])/'state.bundle',Path(actual['path'])/'state.bundle',guard.check);compared+=by_owner[owner]
    base.save(dest/'repeated-a-proof.json',dict(passed=True,full_payload_bytes_compared=compared,bytes_compared_by_owner=by_owner,provider_canonical_sources=73,actual_output_ids_equal=True,actual_output_ids=outputs,initial=first_state,actual=state))
  base.save(dest/'result.json',result);records.append(dict(index=index,id=row['id'],result=result,authority=selected))
  previous=request
 return dict(requests=len(records),request_results=records,bulk_reset_qualified=True,final_target_dump_complete=order==[0,1,0])
