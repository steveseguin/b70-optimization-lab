"""FP8 27B two-card collective A/B, 2026-09-17: the oneCCL allreduce is 47% of device time (134 calls per step at
223 us). The recipe pins CCL_SYCL_ALLREDUCE_SIMPLE_THRESHOLD=4 GiB (since 2026-08-16, no recorded reason), which forces
the ring "simple" kernel for every size. Variants, each on the depth-5 two-card recipe, same session:
  ctrl        current environment (strict only: same-session speed control)
  default     SIMPLE_THRESHOLD=0 so oneCCL picks its small/medium kernels by size: a no-MTP reference (strict, ladder,
              context) then depth 5 (strict, ladder, context, vs that reference)
  ll          default thresholds plus the low-latency allreduce (CCL_SYCL_ALLREDUCE_LL=twoshots, LL threshold 1 MiB):
              depth 5 strict only as a speed screen; gated later if it wins
  service     the two-card package service back on 18124 (unchanged environment), parity vs the no-MTP reference
Identity is gated per environment (a different summation order is a different arithmetic, like a kernel change).
"""

