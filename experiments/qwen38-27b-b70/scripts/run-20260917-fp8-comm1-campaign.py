PROMPTS = [p['prompt'] for p in SUITE['prompts'][:4]]


def post(base, path, body=None, timeout=900):
    data = json.dumps(body).encode() if body is not None else b''
    req = urllib.request.Request(base + path, data=data, headers={'Content-Type': 'application/json'}, method='POST')
    with urllib.request.urlopen(req, timeout=timeout) as response:
        return json.loads(response.read() or b'{}')


TP2 = ['--tp', '2', '--mem', '0.95', '--max-model-len', str(R.TP2_MML), '--batched', '4096', '--fa-verify-rows']
DEPTH5 = ['--mtp', '5', '--draft-int4', '--shortlist', R.SHORTLIST]
DEFAULT_ENV = ['--env', 'CCL_SYCL_ALLREDUCE_SIMPLE_THRESHOLD=0', '--env', 'CCL_SYCL_ALLGATHERV_SIMPLE_THRESHOLD=0', '--env', 'CCL_SYCL_REDUCE_SCATTER_SIMPLE_THRESHOLD=0']
LL_ENV = DEFAULT_ENV + ['--extra-env', 'CCL_SYCL_ALLREDUCE_LL=twoshots', '--extra-env', 'CCL_SYCL_ALLREDUCE_LL_THRESHOLD=1048576']


def gate(name, srv, strict_ref, ladder_ref, ctx_ref, full):
    r = {'server': {k: srv.state.get(k) for k in ('status', 'error', 'ready_at')}}
    if srv.ready:
        r['strict'] = R.strict(srv.base, name, strict_ref) if strict_ref else {'note': 'reference generated by this server'}
        if full:
            lad = R.ladder(srv.base, name, 1)
            r['ladder'] = R.ladder_compare(name, lad, ladder_ref) if ladder_ref else {'ladder': str(lad)}
            r['context'], _ = R.context(srv.base, name, R.TP2_LENGTHS, R.TP2_MML, 2, ctx_ref)
    r['stop'] = srv.stop()
    return r


def main():
    OUT.mkdir(parents=True, exist_ok=False)
    since = R.now()
    R.log(f'comm-1 campaign start; git {subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()}')
    results = R.RESULTS
    results['started'] = since
    R.save_results()
    R.stop_service()
    results['preflight_health_rc'] = R.health('preflight-health')
    R.save_results()
    if results['preflight_health_rc'] != 0:
        raise SystemExit(4)
    R.fault_check(since)

    srv = R.Research('tp2-ctrl-mtp5', 18200, TP2 + DEPTH5)
    results['tp2-ctrl-mtp5'] = gate('tp2-ctrl-mtp5', srv, TP2_STRICT, None, None, False)
    R.save_results(); R.fault_check(since); R.wait_gpus_free()

    srv = R.Research('tp2-default-mtp0', 18201, TP2 + ['--mtp', '0'] + DEFAULT_ENV)
    results['tp2-default-mtp0'] = gate('tp2-default-mtp0', srv, TP2_STRICT, None, None, True)
    R.save_results(); R.fault_check(since); R.wait_gpus_free()
    ref_strict = OUT / 'tp2-default-mtp0-strict'
    ref_ladder = OUT / 'tp2-default-mtp0-ladder.json'
    ref_ctx = OUT / 'tp2-default-mtp0-context/summary.json'
    ok = ref_strict.exists() and ref_ladder.exists() and ref_ctx.exists()

    srv = R.Research('tp2-default-mtp5', 18202, TP2 + DEPTH5 + DEFAULT_ENV)
    results['tp2-default-mtp5'] = gate('tp2-default-mtp5', srv, ref_strict if ok else TP2_STRICT, ref_ladder if ok else None, ref_ctx if ok else None, True)
    R.save_results(); R.fault_check(since); R.wait_gpus_free()

    srv = R.Research('tp2-ll-mtp5', 18203, TP2 + DEPTH5 + LL_ENV)
    results['tp2-ll-mtp5'] = gate('tp2-ll-mtp5', srv, ref_strict if ok else TP2_STRICT, None, None, False)
    R.save_results(); R.fault_check(since); R.wait_gpus_free()

    results['service_health_rc'] = R.health('service-health')
    R.save_results()
    if results['service_health_rc'] != 0:
        raise SystemExit(5)
    state_dir = OUT / 'service'
    unit = 'fp8-service-20260917k'
    argv = ['systemd-run', '--user', '--unit', unit, '--working-directory', str(ROOT), '--collect',
            sys.executable, str(PKG_TP2), 'start', '--model-dir', str(R.MODEL), '--state-dir', str(state_dir), '--port', '18124']
    R.wait_port_free(18124)
    (OUT / 'service.command.json').write_text(json.dumps({'argv': argv, 'started': R.now()}) + '\n')
    subprocess.run(argv, check=True)
    deadline = time.monotonic() + 2400
    state = {}
    while time.monotonic() < deadline:
        if (state_dir / 'state.json').exists():
            state = json.loads((state_dir / 'state.json').read_text())
            if state.get('status') in ('ready', 'failed', 'stopped'):
                break
        time.sleep(10)
    results['service'] = {'status': state.get('status'), 'error': state.get('error'), 'unit': unit, 'state_dir': str(state_dir)}
    R.log(f'service: {state.get("status")} {state.get("error") or ""}')
    if state.get('status') == 'ready':
        results['service']['strict'] = R.strict('http://127.0.0.1:18124', 'service', TP2_STRICT)
    R.save_results(); R.fault_check(since)
    results['finished'] = R.now()
    R.save_results()
    R.log('=== comm-1 campaign complete ===')


if __name__ == '__main__':
    main()
