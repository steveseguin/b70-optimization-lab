#!/usr/bin/env bash
# Round 2 (2026-10-10 night): seed 1 of the 16K arms, then the 32K cap (lossy floors W32/P32 beside B32ir/B32ira) on
# seed 0, same 240K sparse stream with probes. Two-card Qwen3.8-27B FP8 server on port 18196 (window 65,536).
# One arm at a time (host RAM gives concurrency 1). Expected ~3 h; STOP file ends it between arms.
set -uo pipefail
cd /home/steve/b70-optimization-lab/experiments/qwen38-27b-b70/scripts/context || exit 2
export OUT_DIR=${OUT_DIR:-/mnt/fast-ai/bench-results/context-longrun-20261010/client}
export API_BASE=${API_BASE:-http://127.0.0.1:18196/v1}
export MODEL_NAME=${MODEL_NAME:-qwen38-27b-fp8}
export SPARSE_ARGS="--density 3 --words --probes-every 25 --probes-k 3"
export MU_RUN_TIMEOUT=${MU_RUN_TIMEOUT:-7200}
export MAX_TOKENS=${MAX_TOKENS:-8192}
rm -f "$OUT_DIR/STOP"; mkdir -p "$OUT_DIR"
SZ=240000
echo "### round2 start $(date +%F' '%T) MemAvailable $(awk '/^MemAvailable:/ {printf "%d", $2/1024}' /proc/meminfo) MiB"
run_pass() {  # seed arms...
  local seed=$1; shift
  for arm in "$@"; do
    [ -e "$OUT_DIR/STOP" ] && { echo "### stopped by STOP"; return 1; }
    echo "### [$arm s$seed] start $(date +%H:%M)"
    local t0=$SECONDS
    ARMS="$arm" KINDS=sparse SEEDS="$seed" SIZES="$SZ" SUBSET=core ./second-comparison.sh > "$OUT_DIR/arm-$arm-s$seed.out" 2>&1
    echo "### [$arm s$seed] done rc=$? in $(( (SECONDS-t0)/60 )) min $(date +%H:%M)"
    grep -h 'ledger score\|^!!!' "$OUT_DIR/arm-$arm-s$seed.out" | head -2 | cut -c1-160
    curl -sf -m 10 "$API_BASE/models" >/dev/null || { echo "### server gone"; return 1; }
  done
}
# seed 1 stream must exist (generated by the DRY_RUN planning step for W16)
DRY_RUN=1 ARMS=W16 KINDS=sparse SEEDS=1 SIZES="$SZ" SUBSET=core ./second-comparison.sh > "$OUT_DIR/generate-s1.out" 2>&1 || true
[ -f "$OUT_DIR/tasks/sparse-memory/sparse-memory-t240k-s1/task.toml" ] || /mnt/fast-ai/venvs/clm/bin/python make_sparse_prose_tasks.py "$OUT_DIR/tasks/sparse-memory" --tokens $SZ --seeds 1 --mode memory --exact-tokens $SPARSE_ARGS > "$OUT_DIR/tasks/sparse-memory-t240k-s1.gen.json" 2>&1
run_pass 1 W16 D16 B16ir B16ira && run_pass 0 W32 P32 B32ir B32ira
echo "### [analysis] $(date +%H:%M)"
/mnt/fast-ai/venvs/clm/bin/python ./probe_analysis.py "$OUT_DIR" --json "$OUT_DIR/probe-analysis-round2.json" > "$OUT_DIR/probe-analysis-round2.txt" 2>&1 || echo "### analysis rc=$?"
head -40 "$OUT_DIR/probe-analysis-round2.txt"
echo "### round2 complete $(date +%F' '%T)"
