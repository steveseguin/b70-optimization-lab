#!/usr/bin/env python3
"""CPU-only packet audit. Never imports a runtime or executes a model binary."""
import argparse
import hashlib
import json
from pathlib import Path
import statistics
import struct

ROOT = Path(__file__).resolve().parents[3]
RECIPE = Path(__file__).resolve().parents[1]
PACKET = ROOT / "experiments/own-xpu-runtime/stage2/packet44-context"
SUITE = ROOT / "experiments/own-xpu-runtime/stage2/suite-inputs-20261012-cap128/suite-manifest.json"
RESULT = ROOT / "experiments/qwen38-flash-next-ud-iq3xxs-b70/data/20261013-own-rt-iq3-tp2-c4096-realistic-suite-v1-result.json"


def read(path):
    return json.loads(path.read_text())


def sha(path):
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(4 * 1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def verify_suite(directory):
    manifest = read(SUITE)
    summary = read(directory / "summary.json")
    require(summary["passed"] and summary["complete"] and summary["token_cap"] == 128, "incomplete 128-token suite")
    prompts = {p["prompt_id"]: p for p in manifest["prompts"]}
    rows = summary["rows"]
    require(len(prompts) == 12 and len(rows) == 12, "expected exactly twelve cold requests")
    require({r["prompt_id"] for r in rows} == set(prompts), "prompt coverage differs")
    rates = {}
    for row in rows:
        name = row["prompt_id"]
        source = prompts[name]
        oracle_dir = ROOT / source["oracle_directory"]
        require(sha(oracle_dir / "receipt.json") == source["oracle_receipt_sha256"], "oracle receipt changed: " + name)
        oracle = read(oracle_dir / "result.json")
        token_log = [json.loads(line)["token_id"] for line in (oracle_dir / "tokens.jsonl").read_text().splitlines()]
        receipt_path = (directory / row["receipt"]).resolve()
        require(directory.resolve() in receipt_path.parents, "receipt escapes suite directory")
        receipt = read(receipt_path)
        require(row["passed"] and receipt["passed"], "failed request: " + name)
        require(receipt["tokens"] == oracle["tokens"] == token_log and len(token_log) == 128, "token mismatch: " + name)
        require(receipt["oracle_check"]["passed"] and receipt["oracle_check"]["fixture_files"] == 384, "fixture check failed: " + name)
        require(receipt["arithmetic"] == "iq3-p17-detmath-v2" and receipt["controller"] == "native", "runtime identity differs")
        times = receipt["generated_token_completion_timestamps"]
        require(len(times) == 128 and all(a < b for a, b in zip(times, times[1:])), "invalid completion timestamps")
        rate = 99 / (times[99] - times[0])
        require(abs(rate - row["submission_tok_s"]) < 1e-9, "99-interval rate mismatch")
        rates[name] = rate
    result = read(RESULT)
    classes = {}
    for row in result["rows"]:
        classes.setdefault(row["prompt_class"], []).append(rates[row["prompt_id"]])
    value = statistics.median(statistics.median(v) for v in classes.values())
    print(f"suite verified: 12/12 requests, 1536/1536 tokens; class-balanced 99-interval median={value:.12f} tok/s")
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suite-dir", type=Path)
    parser.add_argument("--build-artifacts", action="store_true", help="also hash locally restored binaries; never execute them")
    args = parser.parse_args()
    pins = read(RECIPE / "manifests/evidence.json")
    for name, digest in pins["files"].items():
        require(sha(ROOT / name) == digest, "evidence changed: " + name)
    build = read(PACKET / "build-receipt.json")
    for name, digest in build["sources"].items():
        if name.endswith("packet44-context/build/fusion-rope.hpp"):
            # Generated by build.py prepare; verify the same bytes without a build/write.
            h = hashlib.sha256(b"#pragma once\nnamespace rope_constants { inline constexpr int positions=32768; inline constexpr uint16_t table[]={")
            first = True
            for (value,) in struct.iter_unpack("<H", (PACKET / "rope.bf16").read_bytes()):
                h.update((("" if first else ",") + str(value)).encode())
                first = False
            h.update(b"};}\n")
            require(h.hexdigest() == digest, "generated RoPE header differs")
        else:
            require(sha(ROOT / name) == digest, "sealed source changed: " + name)
    if args.build_artifacts:
        for name, digest in build["artifacts_sha256"].items():
            require(sha(PACKET / "build" / name) == digest, "build artifact changed: " + name)
    for chain in ("receipts-cards01-20261013-c4096", "receipts-cards23-20261013-c32768"):
        verify_suite(PACKET / chain / "WS128")
    if args.suite_dir:
        verify_suite(args.suite_dir)
    print(f"health PASS: {len(pins['files'])} evidence hashes, {len(build['sources'])} sealed sources; CPU only; no live device health claim")


if __name__ == "__main__":
    main()
